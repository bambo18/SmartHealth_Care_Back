-- V49__add_walk_light_sensor_samples.sql
--
-- 반려견 산책 중 스마트폰 조도 센서 측정 기능 추가
--
-- 변경 사항
-- 1. 진행 중인 산책을 표현하기 위해 walks.end_time NULL 허용
-- 2. 스마트폰에서 측정한 조도(Lux) 원본 데이터 저장 테이블 생성
-- 3. 동일 센서 데이터 중복 저장 방지
-- 4. 산책별 시간순 조도 데이터 조회를 위한 인덱스 생성
-- ============================================================


-- ============================================================
-- 1. walks.end_time NULL 허용
-- ============================================================
--
-- 산책 시작 시점에는 종료 시간이 아직 존재하지 않으므로
-- 진행 중인 산책의 end_time은 NULL이 될 수 있어야 한다.
--
-- 산책 종료 API 호출 시 end_time을 저장한다.
-- ============================================================

ALTER TABLE walks
    ALTER COLUMN end_time DROP NOT NULL;


-- ============================================================
-- 2. 조도 센서 측정값 저장 테이블
-- ============================================================

CREATE TABLE light_sensor_samples (

    -- PK
    id BIGSERIAL PRIMARY KEY,

    -- 조도가 측정된 산책
    walk_id BIGINT NOT NULL,

    -- 스마트폰 앱에서 각각의 센서 측정값에 부여하는 UUID
    --
    -- 예)
    -- 앱이 데이터를 서버로 전송했는데 응답을 받지 못한 경우
    -- 동일 데이터를 재전송할 수 있다.
    --
    -- 이 값을 이용해 동일 측정값이 중복 저장되는 것을 방지한다.
    client_sample_id UUID NOT NULL,

    -- 스마트폰에서 실제 조도를 측정한 시간
    --
    -- 서버에 데이터가 도착한 시간이 아니라
    -- 스마트폰 센서에서 값을 얻은 실제 시간을 사용한다.
    measured_at TIMESTAMPTZ NOT NULL,

    -- 스마트폰 조도 센서에서 측정한 값
    -- 단위: Lux
    lux DOUBLE PRECISION NOT NULL,

    -- 서버 DB에 데이터가 저장된 시간
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,


    -- ========================================================
    -- Foreign Key
    -- ========================================================
    --
    -- 해당 산책이 삭제되면
    -- 그 산책에서 측정한 조도 데이터도 함께 삭제한다.
    -- ========================================================

    CONSTRAINT fk_light_sensor_samples_walk
        FOREIGN KEY (walk_id)
        REFERENCES walks(id)
        ON DELETE CASCADE,


    -- ========================================================
    -- 중복 측정값 방지
    -- ========================================================
    --
    -- 같은 산책에서 동일 client_sample_id는
    -- 한 번만 저장할 수 있다.
    -- ========================================================

    CONSTRAINT uq_light_sensor_samples_walk_client_sample
        UNIQUE (walk_id, client_sample_id),


    -- ========================================================
    -- Lux 값 검증
    -- ========================================================
    --
    -- 조도값은 음수가 될 수 없으므로
    -- DB에서도 음수값 저장을 차단한다.
    -- ========================================================

    CONSTRAINT chk_light_sensor_samples_lux
        CHECK (lux >= 0)
);


-- ============================================================
-- 3. 조회 성능용 인덱스
-- ============================================================
--
-- 이후 백엔드에서 다음과 같은 조회를 자주 하게 된다.
--
-- 특정 산책의 조도 측정값을
-- measured_at 순서대로 조회
--
-- 따라서 walk_id + measured_at 복합 인덱스를 생성한다.
-- ============================================================

CREATE INDEX idx_light_sensor_samples_walk_measured_at
    ON light_sensor_samples (walk_id, measured_at);