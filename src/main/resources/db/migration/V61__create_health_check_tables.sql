
-- V61: Create self health check history tables

-- 1. 자가 건강 진단 기록
CREATE TABLE health_check_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    pet_id BIGINT NOT NULL,
    species VARCHAR(10) NOT NULL,
    overall_stage SMALLINT NOT NULL,
    scoring_version VARCHAR(30) NOT NULL DEFAULT 'v1',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_health_check_records_pet
        FOREIGN KEY (pet_id)
        REFERENCES pets(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_health_check_species
        CHECK (species IN ('DOG', 'CAT')),

    CONSTRAINT chk_health_check_overall_stage
        CHECK (overall_stage BETWEEN 1 AND 4)
);

-- 2. 영역별 점수 및 판정
CREATE TABLE health_check_areas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    record_id BIGINT NOT NULL,
    area_key VARCHAR(30) NOT NULL,
    area_title VARCHAR(100) NOT NULL,

    score INTEGER NOT NULL,
    stage SMALLINT NOT NULL,
    urgent_hit BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_health_check_areas_record
        FOREIGN KEY (record_id)
        REFERENCES health_check_records(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_health_check_record_area
        UNIQUE (record_id, area_key),

    CONSTRAINT chk_health_check_area_score
        CHECK (score BETWEEN 0 AND 100),

    CONSTRAINT chk_health_check_area_stage
        CHECK (stage BETWEEN 1 AND 4)
);

-- 3. 문항별 응답 상세
CREATE TABLE health_check_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    area_id BIGINT NOT NULL,
    question_index INTEGER NOT NULL,
    question_text TEXT NOT NULL,

    question_weight VARCHAR(10) NOT NULL,
    answer_value SMALLINT NOT NULL,

    CONSTRAINT fk_health_check_answers_area
        FOREIGN KEY (area_id)
        REFERENCES health_check_areas(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_health_check_area_question
        UNIQUE (area_id, question_index),

    CONSTRAINT chk_health_check_question_index
        CHECK (question_index >= 0),

    CONSTRAINT chk_health_check_answer_value
        CHECK (answer_value BETWEEN 0 AND 3),

    CONSTRAINT chk_health_check_question_weight
        CHECK (question_weight IN ('1', '2', '3', 'urgent'))
);

-- 조회 성능을 위한 인덱스
CREATE INDEX idx_health_check_records_pet_created
    ON health_check_records (pet_id, created_at DESC, id DESC);

CREATE INDEX idx_health_check_areas_record
    ON health_check_areas (record_id);

CREATE INDEX idx_health_check_answers_area
    ON health_check_answers (area_id);
